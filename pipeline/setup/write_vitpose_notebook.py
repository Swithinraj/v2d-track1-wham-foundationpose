def cell(kind: str, source: str, number: int) -> dict:
    cleaned = dedent(source).lstrip("\n")
    if cleaned.startswith("    "):
        # A nested multiline Python string can keep dedent() from removing
        # the notebook cell's four-space margin. Preserve indentation inside it.
        lines = []
        inside_literal = False
        for line in cleaned.splitlines(keepends=True):
            if not inside_literal and line.startswith("    "):
                line = line[4:]
            lines.append(line)
            if "'''" in line:
                inside_literal = not inside_literal
        cleaned = "".join(lines)
    item = {
        "cell_type": kind,
        "id": f"v2d-vitpose-{number}",
        "metadata": {},
        "source": cleaned.splitlines(keepends=True),
    }
    if kind == "code":
        item.update(execution_count=None, outputs=[])
    return item


