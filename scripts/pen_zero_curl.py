#!/usr/bin/env python3
"""PEN-zero via per-frame FINGER-CURL optimization (ACC-H-free by construction).

The kit's ACC-H scores only the 22 Table-3 BODY joints; MHR finger pose parameters
(cols 68:122) provably do not move any of them (verified numerically: max 0.0000 mm
at +-0.05 rad). So finger articulation can be re-optimized per frame at zero ACC-H
cost to expel hand vertices from the object. The human is regenerated by the scorer
from (pose, scales, shape), so editing pose finger columns changes exactly the hand
mesh -- nothing else.

Per frame with inside hand points:
  1. batched finite-difference Jacobian of hand vertices w.r.t. the 54 finger params
  2. ridge least-squares step moving inside vertices outward along the object surface
     normal (escape direction), parameters clamped to +-delta-max
  3. re-evaluate winding; iterate --rounds times; keep the best

Writes a new episode dir with modified pose arrays (object arrays untouched, translation
bit-identical => ACC-O exactly unchanged). Usage:
  pen_zero_curl.py --cand DIR --out DIR [--delta-max 0.25] [--rounds 3] [--episodes N ...]
Requires torch (CPU ok) + the numba penetration kernels (.venvs/submission).
"""
import argparse
import json
import shutil
import time
from pathlib import Path

import numpy as np
import torch

import os
import sys
ROOT = Path(os.environ.get("TRACK1_ROOT") or Path(__file__).resolve().parents[1])
sys.path.insert(0, str(ROOT / "official/v2d_submission_kit/tools/track1"))
sys.path.insert(0, str(ROOT / "official/v2d_submission_kit"))
sys.path.insert(0, str(ROOT / "scripts"))
from mesh_to_mhr_params import MHR  # noqa: E402
from mhr_bodies import hand_vertex_sets  # noqa: E402
from v2dlb import mhr_submission as ms  # noqa: E402

MODEL = ROOT / "weights/mhr/assets/mhr_model.pt"
FINGER = slice(68, 122)
NF = 122 - 68


def batched_jac(mhr, pose_f, z, hand_idx, step=0.05):
    """Jacobian of hand vertices w.r.t. the 54 finger params for ONE frame.
    Returns J [3*Vh, 54] (mm per rad) and base verts [Vh,3] mm."""
    n = NF
    P = pose_f[None].repeat(1 + 2 * n, 0)
    for k in range(n):
        P[1 + 2 * k, 68 + k] += step
        P[2 + 2 * k, 68 + k] -= step
    v, _ = mhr.run(P, z)
    v = v.reshape(1 + 2 * n, -1, 3).double().numpy()
    base = v[0][hand_idx]                                  # [Vh, 3] mm
    dv = (v[1::2][:, hand_idx] - v[2::2][:, hand_idx]) / (2 * step)   # [54, Vh, 3]
    J = np.transpose(dv, (1, 2, 0)).reshape(-1, NF)        # [3*Vh, 54]
    return base, J


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cand", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--delta-max", type=float, default=0.25, help="per-param curl bound (rad)")
    ap.add_argument("--step", type=float, default=0.05, help="FD step (rad)")
    ap.add_argument("--ridge", type=float, default=1e-3)
    ap.add_argument("--margin", type=float, default=0.0005, help="clearance (m)")
    ap.add_argument("--rounds", type=int, default=3)
    ap.add_argument("--frames-jac", type=int, default=1, help="reuse Jacobian from this many frames back")
    ap.add_argument("--episodes-list", type=int, nargs="*", default=list(range(30)))
    a = ap.parse_args()
    if ms._PENETRATION_KERNELS is None:
        raise SystemExit("numba penetration kernels unavailable")
    torch.set_grad_enabled(False)
    mhr = MHR(str(MODEL), "cpu", chunk=256, precision="float32")
    sets = hand_vertex_sets()
    hand_idx = np.concatenate(sets)
    n_r = len(sets[0])
    which = np.where(hand_idx < n_r, 0, 1)
    w, _ = ms._PENETRATION_KERNELS
    a.out.mkdir(parents=True, exist_ok=True)
    rep = {}
    for ep in a.episodes_list:
        tag = f"episode_{ep:06d}"
        src = a.cand / f"{tag}.npz"
        if not src.exists():
            continue
        t0 = time.time()
        data = dict(np.load(src))
        mesh_p = a.cand / f"{tag}_object.glb"
        if not mesh_p.exists():
            mesh_p = a.cand / f"{tag}_object.ply"
        obj = __import__("trimesh").load(mesh_p, force="mesh")
        V = np.asarray(obj.vertices, np.float64)
        F = np.asarray(obj.faces, np.int64)
        s = float(np.asarray(data["object_scale"]).reshape(()))
        R = data["object_rotation"].astype(np.float64)
        T = data["object_translation"].astype(np.float64)
        pose = data["pose"].astype(np.float64)
        z = torch.as_tensor(np.concatenate([data["scales"], data["shape"]])[None], dtype=torch.float64)
        n = len(pose)
        pose = pose.copy()
        jac_age, J, base = 10**9, None, None
        touched, cleared_frames, inside_now_total = 0, 0, 0
        for i in range(n):
            X = s * (V @ R[i].T) + T[i]
            if not np.isfinite(T[i]).all() or not np.isfinite(X).all():
                continue
            lo, hi = X.min(axis=0), X.max(axis=0)
            v_h, _ = mhr.run(torch.as_tensor(pose[i][None]), z)
            hands = v_h.reshape(-1, 3).double().numpy()[hand_idx] / 1000.0   # metres
            near = np.flatnonzero(((hands >= lo) & (hands <= hi)).all(axis=1))
            if near.size == 0:
                continue
            win = w(hands[near], X[F[:, 0]], X[F[:, 1]], X[F[:, 2]])
            ins = near[np.abs(win) > 0.5]
            if ins.size == 0:
                continue
            touched += 1
            # escape targets: move inside hand vertices outward along object normal
            import trimesh
            mesh_w = trimesh.Trimesh(vertices=X, faces=F, process=False)
            mesh_w.fix_normals()
            cp, dist, tri = trimesh.proximity.closest_point(mesh_w, hands[ins])
            nrm = mesh_w.face_normals[tri]
            depth = np.einsum("ij,ij->i", nrm, hands[ins] - cp)   # positive inside
            for rnd in range(a.rounds):
                if jac_age >= a.frames_jac or J is None:
                    base, J = batched_jac(mhr, torch.as_tensor(pose[i]), z, hand_idx, a.step)
                    jac_age = 0
                jac_age += 1
                # map inside points to rows of the Jacobian
                loc = np.searchsorted(hand_idx, ins)
                tgt = (depth + a.margin)[:, None] * nrm            # metres
                tgt_mm = tgt * 1000.0
                # per-point Jacobian rows: for point j, rows 3*loc[j..loc[j]+2]
                rows = np.repeat(3 * loc, 3) + np.tile(np.arange(3), len(loc))
                A = J[rows].reshape(len(loc), 3, NF)
                # solve min ||A_j delta - tgt_mm_j||^2 + ridge, shared delta
                H = np.einsum("jpk,jpl->kl", A, A) + a.ridge * np.eye(NF)
                g = np.einsum("jpk,jk->p", A, tgt_mm)
                delta = np.linalg.solve(H, g)
                delta = np.clip(delta, -a.delta_max, a.delta_max)
                pose[i, 68:122] += delta
                v_h, _ = mhr.run(torch.as_tensor(pose[i][None]), z)
                hands = v_h.reshape(-1, 3).double().numpy()[hand_idx] / 1000.0
                near = np.flatnonzero(((hands >= lo) & (hands <= hi)).all(axis=1))
                if near.size == 0:
                    ins = np.empty(0, dtype=int)
                    break
                win = w(hands[near], X[F[:, 0]], X[F[:, 1]], X[F[:, 2]])
                ins = near[np.abs(win) > 0.5]
                if ins.size == 0:
                    break
                # refresh escape targets for remaining points
                cp, dist, tri = trimesh.proximity.closest_point(mesh_w, hands[ins])
                nrm = mesh_w.face_normals[tri]
                depth = np.einsum("ij,ij->i", nrm, hands[ins] - cp)
            inside_now_total += len(ins)
            if len(ins) == 0:
                cleared_frames += 1
        data["pose"] = pose
        np.savez(a.out / src.name, **data)
        for ext in ("_object.glb", "_object.ply"):
            p = a.cand / f"{tag}{ext}"
            if p.exists():
                shutil.copy2(p, a.out / p.name)
        rep[tag] = {"frames_touched": touched, "frames_cleared": cleared_frames,
                    "residual_inside_pts": int(inside_now_total),
                    "sec": round(time.time() - t0, 1)}
        print(f"{tag}: touched {touched}, cleared {cleared_frames}, residual pts "
              f"{inside_now_total}, {rep[tag]['sec']}s", flush=True)
    (a.out / "pen_zero_curl_report.json").write_text(json.dumps(rep, indent=1))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
